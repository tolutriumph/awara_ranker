resolve1 <- function(raw_name) {            # returns c(canonical, method) for one raw name
  k <- norm(raw_name)
  if (raw_name %in% non_state)                          return(c(NA, "non_state_row"))
  if (raw_name %in% canon)                              return(c(raw_name, "exact"))
  if (k %in% names(alias) && alias[[k]] %in% canon)     return(c(unname(alias[[k]]), "manual_alias"))
  if (k %in% canon_key)                                 return(c(canon[match(k, canon_key)], "normalised_spelling"))
  c(NA, "UNMATCHED")
}
make_lookup <- function(src, raw) {
  u <- unique(raw); r <- t(vapply(u, resolve1, character(2)))
  tibble(source_file = src, raw_name = u, canonical_name = r[, 1], match_method = r[, 2])
}

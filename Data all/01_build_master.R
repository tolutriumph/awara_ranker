audit <- function(name, x, level, units) {
  na <- colSums(is.na(x))
  alog("=== ", name, " ===")
  alog("rows: ", nrow(x), " | cols: ", ncol(x), " | level: ", level)
  alog("likely units: ", units)
  alog("types: ", paste0(names(x), ":", vapply(x, function(v) class(v)[1], ""), collapse = ", "))
  alog("missing per column: ", if (any(na > 0)) paste0(names(na)[na > 0], "=", na[na > 0], collapse = ", ") else "none")
  alog("first 3 rows:")
  h <- head(as.data.frame(x), 3) %>% mutate(across(everything(), ~ substr(as.character(.x), 1, 28)))
  LOG <<- c(LOG, capture.output(if (ncol(h) > 10) print(t(h)) else print(h, row.names = FALSE)))
  alog("")
  SUMM <<- bind_rows(SUMM, tibble(file = name, rows = nrow(x), cols = ncol(x), level = level, cols_with_NA = sum(na > 0)))
}

